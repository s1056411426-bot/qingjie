// Export original IconPark SVGs with its official renderer. Do not redraw paths.
const fs=require('node:fs');
const path=require('node:path');
const library=require('@icon-park/svg');
const catalog=require('@icon-park/svg/icons.json');
const version=require('@icon-park/svg/package.json').version;
const mapping={
  capture:['ScreenshotOne','开始截图'],crop:['Tailoring','裁剪'],
  grid:['AllApplication','工作台'],history:['History','截图历史'],settings:['SettingTwo','偏好设置'],
  arrow:['ArrowRightUp','箭头 / 查看全部'],down:['ArrowDown','滚动长截图'],upload:['UploadPicture','导入图片'],
  screen:['MonitorOne','全屏截图'],window:['Browser','窗口截图'],scan:['TextRecognition','提取文字'],
  pin:['Pushpin','贴图 / 置顶'],copy:['Copy','复制'],save:['Save','保存'],
  close:['Close','关闭 / 取消'],check:['Check','完成 / 保存设置'],plus:['Plus','新增 / 放大'],minus:['Minus','缩小'],
  back:['ArrowLeft','返回'],redo:['Redo','重做'],undo:['Undo','撤销'],
  rect:['Rectangle','矩形'],ellipse:['OvalOne','椭圆'],pen:['Pencil','画笔 / 标注编辑'],
  line:['Minus','直线'],text:['Text','文字标注'],mosaic:['Mosaic','马赛克'],marker:['HighLight','荧光笔'],
  number:['ListNumbers','序号标注'],color:['Platte','取色'],qr:['TwoDimensionalCode','二维码识别'],
  trash:['Delete','删除历史'],image:['PictureOne','图片 / 空状态'],shield:['Protect','本地处理'],
  clock:['Time','延时截图'],folder:['FolderOpen','文件夹'],keyboard:['Keyboard','快捷键'],spark:['Star','装饰星标']
};
const root=path.resolve(__dirname,'..'),svgs={},rows=[];
for(const [key,[name,label]] of Object.entries(mapping)){
  if(typeof library[name]!=='function')throw Error('Unknown IconPark icon: '+name);
  const slug=name.replace(/([a-z0-9])([A-Z])/g,'$1-$2').toLowerCase();
  const metadata=catalog.find(item=>item.name===slug);
  if(!metadata)throw Error('Missing provenance: '+name);
  // Only strip the XML document declaration for safe inline HTML insertion.
  svgs[key]=library[name]({theme:'outline',size:20,fill:'currentColor',strokeWidth:4,strokeLinecap:'round',strokeLinejoin:'round'}).replace(/^<\?xml[^>]*\?>/,'');
  rows.push(`| ${label} | ${name} | ${metadata.title} | ${metadata.author} |`);
}
fs.writeFileSync(path.join(root,'src/ui/iconpark-data.js'),`// Generated by scripts/icons.cjs from @icon-park/svg ${version}.\n// Copyright 2019-present Bytedance Inc. Apache-2.0; see iconpark/LICENSE.\nexport const iconpark=${JSON.stringify(svgs,null,2)};\n`);
fs.mkdirSync(path.join(root,'src/ui/iconpark'),{recursive:true});
fs.copyFileSync(require.resolve('@icon-park/svg/LICENSE'),path.join(root,'src/ui/iconpark/LICENSE'));
fs.writeFileSync(path.join(root,'docs/IconPark图标映射.md'),`# IconPark 原版图标映射\n\n来源：[IconPark 官方图标库](https://iconpark.oceanengine.com/official)、[官方源码](https://github.com/bytedance/IconPark)。使用官方包 @icon-park/svg ${version}，Apache-2.0 授权。\n\n直接调用官方 SVG 导出函数，使用 outline 主题、原生 48×48 viewBox、4 单位线宽和 currentColor。路径、形状及比例没有手工改画；仅移除 XML 声明，显示时设置尺寸及无障碍属性。应用 Logo 使用用户原图。\n\n运行 npm run icons 可重新生成。选中的 SVG 本地打包，运行时无需访问网站。\n\n| 轻截功能 | 官方组件 | 官方名称 | 原作者 |\n| --- | --- | --- | --- |\n${rows.join('\n')}\n\n说明：取色使用官方调色盘 Platte；序号使用 ListNumbers；直线使用 Minus。这些是库中现有图标的功能映射，没有拼接或重绘。\n`);
console.log(`Exported ${Object.keys(svgs).length} original IconPark SVG mappings (${version}).`);
